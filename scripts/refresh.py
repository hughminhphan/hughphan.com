#!/usr/bin/env python3
"""Pull live GitHub numbers into gh-data.js (stars, languages, contribution calendar).

Run from anywhere: python3 scripts/refresh.py
Needs the gh CLI signed in as hughminhphan. Content (blurbs, which repos show) lives in content.js.
"""
import json
import pathlib
import subprocess
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parent.parent
USER = "hughminhphan"


def gh(*args):
    return json.loads(subprocess.check_output(["gh", *args], text=True))


profile = gh("api", f"users/{USER}")
repos = gh("api", f"users/{USER}/repos?per_page=100&type=owner")
cal = gh(
    "api", "graphql", "-f",
    "query={ viewer { contributionsCollection { contributionCalendar { totalContributions "
    "weeks { contributionDays { date contributionCount } } } } } }",
)["data"]["viewer"]["contributionsCollection"]["contributionCalendar"]

public = [r for r in repos if not r["private"] and not r["fork"]]
data = {
    "updated": date.today().isoformat(),
    "since": profile["created_at"][:4],
    "publicRepos": len(public),
    "stars": sum(r["stargazers_count"] for r in public),
    "repos": {
        r["name"]: {
            "stars": r["stargazers_count"],
            "lang": r["language"],
            "pushed": r["pushed_at"][:10],
            "created": r["created_at"][:10],
            "url": r["html_url"],
            "homepage": r["homepage"] or None,
        }
        for r in public
    },
    "contributions": {
        "total": cal["totalContributions"],
        "days": [[d["date"], d["contributionCount"]] for w in cal["weeks"] for d in w["contributionDays"]],
    },
}

out = ROOT / "gh-data.js"
out.write_text("// generated by scripts/refresh.py, do not edit by hand\nwindow.GH = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out.name}: {data['publicRepos']} public repos, {data['stars']} stars, {data['contributions']['total']} contributions")
